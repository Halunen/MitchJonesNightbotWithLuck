const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
test('giveaways remember winners automatically across restarts without an import step', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mitchlucky-test-'));
  const port = 31887, origin = `http://127.0.0.1:${port}`;
  let child;
  async function start() {
    child = spawn(process.execPath, ['server.js'], { cwd: path.join(__dirname, '..'), env: { ...process.env, PORT: String(port), DATA_DIR: dir }, stdio: ['ignore', 'pipe', 'pipe'] });
    await new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error('Server did not start')), 10000); child.stdout.once('data', () => { clearTimeout(timeout); resolve(); }); child.once('error', reject); });
  }
  async function stop() { await new Promise(resolve => { child.once('exit', resolve); child.kill(); }); }
  t.after(() => { if (child && child.exitCode === null) child.kill(); });
  await start();
  const post = async (action, body = {}, customOrigin = origin) => { const response = await fetch(`${origin}/api/${action}`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: customOrigin }, body: JSON.stringify(body) }); return { status: response.status, body: response.status === 403 ? null : await response.json() }; };
  assert.equal((await post('demo', {}, 'https://attacker.example')).status, 403);
  assert.equal((await post('connect', { channel: 'testchannel', writeEnabled: true })).status, 400);
  assert.equal((await post('chat/send', { message: 'Hello' })).status, 400);
  assert.equal((await fetch(origin + '/api/demo/paid-winners')).status, 404);
  assert.equal((await post('demo/payouts/refresh')).status, 400);
  let result = await post('demo'); assert.equal(result.body.round.entrants.length, 12); assert.equal(result.body.demo, true);
  assert.deepEqual(result.body.round.entrants.slice(0, 4).map(e => e.displayName), ['CDEW', 'AndyM', 'CUDA', 'GJake']);
  assert.equal(new Set(result.body.round.entrants.map(e => e.login)).size, 12);
  assert.equal(result.body.round.keyword, 'yo');
  assert.equal(result.body.canSend, true);
  assert.ok(result.body.round.entrants.every(e => e.paidWinner === undefined));
  assert.equal(result.body.payouts.selectedWinner, null);
  assert.equal(result.body.payouts.source, 'demo');
  assert.ok(Date.parse(result.body.payouts.checkedAt));
  const payoutResponse = await (await fetch(origin + '/api/demo/paid-winners')).json();
  assert.equal(payoutResponse.demo, true);
  result = await post('demo/payouts/refresh');
  assert.equal(result.body.payouts.selectedWinner, null);
  assert.equal((await post('chat/send', { message: 'bad\nmessage' })).status, 400);
  result = await post('winner-message', { channel: '__demo__', template: 'Congratulations {winner}! You won.' });
  assert.equal(result.status, 200);
  assert.equal(result.body.winnerMessageTemplate, 'Congratulations {winner}! You won.');
  assert.equal((await post('settings', { boost: 50, cooldownMinutes: 0, keyword: '!luck' })).status, 400);
  const roundId = result.body.round.id;
  assert.equal((await post('luck', { roundId: 'old-round', boost: 40 })).status, 400);
  assert.equal((await post('luck', { roundId, boost: 51 })).status, 400);
  result = await post('luck', { roundId, boost: 40 });
  assert.equal(result.body.round.status, 'open'); assert.equal(result.body.round.boost, 40);
  assert.equal(result.body.round.entrants.length, 12);
  assert.ok(result.body.round.entrants.every(e => e.luckEntries === 1));
  await post('close'); result = await post('open');
  assert.ok(result.body.round.entrants.every(e => e.luckEntries === 1));
  const poolBeforeDraw = result.body.round.entrants;
  const totalWeight = poolBeforeDraw.reduce((sum, e) => sum + e.weight, 0);
  result = await post('draw', { roundId, boost: 45 }); assert.equal(result.body.round.status, 'drawn');
  const selectedPayout = payoutResponse.winners.find(w => w.username.toLowerCase() === result.body.round.winner.login);
  assert.equal(result.body.payouts.selectedWinner?.winCount || 0, selectedPayout?.wins || 0);
  assert.equal(result.body.payouts.selectedWinner?.totalPaidCents || 0, (selectedPayout?.totalPaid || 0) * 100);
  const winner = result.body.round.winner; assert.ok(winner.login); assert.equal((await post('draw')).status, 400);
  assert.equal(winner.boost, 45); assert.equal(winner.odds, poolBeforeDraw.find(e => e.login === winner.login).weight / totalWeight);
  assert.equal((await post('luck', { roundId, boost: 50 })).status, 400);
  assert.equal(result.body.history.filter(h => h.id === winner.id).length, 1);
  assert.equal(result.body.bot, undefined);
  assert.equal((await post('import', { names: 'OLDWINNER' })).status, 400);
  assert.equal((await post('bot/save', {})).status, 400);
  await stop(); await start();
  result = { body: await (await fetch(`${origin}/api/state`)).json() };
  assert.ok(result.body.history.some(h => h.id === winner.id));
  assert.equal(result.body.round.winner.at, winner.at);
  result = await post('demo');
  const returningWinner = result.body.round.entrants.find(e => e.login === winner.login);
  if (returningWinner) assert.equal(returningWinner.weight, 100);
  const repeat = result.body.round.entrants.find(e => e.login === 'cuda');
  assert.equal(repeat.luckEntries, 2); assert.equal(repeat.weight, repeat.wins ? 100 : 110);
  await stop(); await start();
  result = { body: await (await fetch(`${origin}/api/state`)).json() };
  assert.equal(result.body.round.entrants.find(e => e.login === repeat.login).luckEntries, 2);
  await post('new');
  assert.equal((await post('settings', { title: 'Test', keyword: '!LUCK', boost: 25, cooldownMinutes: 0 })).status, 400);
  assert.equal((await post('settings', { title: 'Test', keyword: '!enter', boost: 25, cooldownMinutes: 60 })).status, 200);
  assert.equal((await post('settings', { title: 'Test', keyword: '!enter', boost: 25, cooldownMinutes: -1 })).status, 400);
  assert.equal((await post('settings', { title: 'Test', keyword: '!enter', boost: 25, cooldownMinutes: 43201 })).status, 400);
  result = await post('new'); assert.equal(result.body.round.cooldownMinutes, 60);
  const saved = JSON.parse(fs.readFileSync(path.join(dir, 'state.json')));
  assert.ok(saved.histories.__demo__.some(h => h.id === winner.id)); assert.equal(JSON.stringify(saved).includes('token'), false);
  assert.equal(JSON.stringify(saved).includes('totalPaidCents'), false);
  assert.deepEqual(await (await fetch(origin + '/api/demo/paid-winners')).json(), payoutResponse);
});
